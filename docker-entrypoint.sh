#!/bin/sh
# Старт контейнера: однаково на staging і prod. Міграції виконуються тут, в образі:
# раннер CI не має доступу до БД і не заходить на машину по SSH.
set -e

# 1. Структура: блокуючий, швидкий крок. Якщо він впав, контейнер не стартує
#    і трафік на нову версію не йде (стара версія продовжує працювати).
node scripts/migrate.js schema

# 2. Початкові дані: окремо від міграцій і лише коли явно ввімкнено (SEED=true).
if [ "$SEED" = "true" ]; then
  node scripts/migrate.js seed
fi

# 3. Оновлення даних та індекси: у фоні. Застосунок уже приймає запити,
#    тож довгий крок не викликає циклу "таймаут → падіння → рестарт".
( node scripts/migrate.js data && node scripts/migrate.js indexes ) &

exec node index.js
